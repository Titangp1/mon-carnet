const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('carnet', {
  load: () => ipcRenderer.invoke('carnet:load'),
  save: (text) => ipcRenderer.invoke('carnet:save', text),
  saveSync: (text) => ipcRenderer.sendSync('carnet:saveSync', text),
  exportBackup: (text) => ipcRenderer.invoke('carnet:export', text),
  importBackup: () => ipcRenderer.invoke('carnet:import'),
  openFolder: () => ipcRenderer.invoke('carnet:openFolder'),
  icalFetch: (url) => ipcRenderer.invoke('carnet:icalFetch', url),
  icalCached: () => ipcRenderer.invoke('carnet:icalCached'),
  invoicePdf: (html, name, isNew) => ipcRenderer.invoke('carnet:invoicePdf', html, name, isNew),
  invoiceFiles: () => ipcRenderer.invoke('carnet:invoiceFiles'),
  openPath: (p) => ipcRenderer.invoke('carnet:openPath', p),
  openInvoices: () => ipcRenderer.invoke('carnet:openInvoices'),
  saveText: (name, text) => ipcRenderer.invoke('carnet:saveText', name, text),
  focus: () => ipcRenderer.send('carnet:focus'),
  saroolLogin: () => ipcRenderer.invoke('sarool:login'),
  saroolFetch: () => ipcRenderer.invoke('sarool:fetch'),
  saroolLogout: () => ipcRenderer.invoke('sarool:logout'),
  saroolAgenda: (opts) => ipcRenderer.invoke('sarool:agenda', opts),
  saroolBook: (slot, opts) => ipcRenderer.invoke('sarool:book', slot, opts),
  saroolOpen: () => ipcRenderer.invoke('sarool:open'),
  saroolJournal: () => ipcRenderer.invoke('sarool:journal'),
  mailStatus: () => ipcRenderer.invoke('mail:status'),
  mailSetAccount: (user, pass) => ipcRenderer.invoke('mail:setAccount', user, pass),
  mailRemoveAccount: () => ipcRenderer.invoke('mail:removeAccount'),
  mailCached: () => ipcRenderer.invoke('mail:cached'),
  mailSync: (opts) => ipcRenderer.invoke('mail:sync', opts),
  mailBody: (id) => ipcRenderer.invoke('mail:body', id),
  mailSearch: (opts) => ipcRenderer.invoke('mail:search', opts),
  mailAttachment: (id, name, mode) => ipcRenderer.invoke('mail:attachment', id, name, mode),
  aiChat: (payload) => ipcRenderer.invoke('ai:chat', payload),
  onAiDelta: (fn) => ipcRenderer.on('ai:delta', (_e, x) => fn(x)),
  aiSetKey: (k, id) => ipcRenderer.invoke('ai:setKey', k, id),
  aiUsage: () => ipcRenderer.invoke('ai:usage'),
  aiSetOrder: (order, auto) => ipcRenderer.invoke('ai:setOrder', order, auto),
  aiBench: () => ipcRenderer.invoke('ai:bench'),
  aiResetUsage: () => ipcRenderer.invoke('ai:resetUsage'),
  aiKeyInfo: () => ipcRenderer.invoke('ai:keyInfo'),
  aiPing: () => ipcRenderer.invoke('ai:ping'),
  aiTranscribe: (data, mime) => ipcRenderer.invoke('ai:transcribe', data, mime),
  setPrefs: (p) => ipcRenderer.invoke('app:prefs', p),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateState: () => ipcRenderer.invoke('update:state'),
  updateApply: () => ipcRenderer.invoke('update:apply'),
  updateJournal: () => ipcRenderer.invoke('update:journal'),
  onUpdate: (fn) => ipcRenderer.on('update:state', (_e, s) => fn(s)),
  quit: () => ipcRenderer.send('app:quit'),
  onCommand: (fn) => ipcRenderer.on('app:command', (_e, c) => fn(String(c)))
});
